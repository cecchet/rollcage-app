// Pre-renders the Rollcage library's template thumbnails (their 3D
// snapshots), so the library doesn't draw them all in the browser each
// time: images/templates/model-3d/<id>.jpg plus template-thumbs.js, which
// lists each one with the hash of the design it was drawn from (see
// templateThumb in app.js -- a stale one is drawn live instead). Re-run
// after changing templates.js or the 3D model's look (and bump
// TEMPLATE_THUMB_REV in app.js for the latter), with the app served at
// http://localhost:5003:
//   node tools/manual/driver.mjs tools/template-thumbs.mjs 1280 900
import { writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";

const app = join(dirname(new URL(import.meta.url).pathname.replace(/^\/(\w:)/, "$1")), "..");
const dir = join(app, "images", "templates", "model-3d");

export default async function (a) {
  await a.go("http://localhost:5003/");
  // Ignore the current pre-rendered ones, open the library and wait until
  // every template's snapshot is drawn.
  const shots = await a.eval(`
    const wait = (ms) => new Promise((r) => setTimeout(r, ms));
    await wait(500);
    const exit = [...document.querySelectorAll('button')].find((b) => /Exit the tutorial/.test(b.textContent));
    if (exit) exit.click();
    await wait(500);
    window.TEMPLATE_MODEL_THUMBS = {};
    if (!document.getElementById('library-dialog')) [...document.querySelectorAll('button')].find((b) => /^Rollcage library$/.test(b.textContent.trim())).click();
    for (let i = 0; i < 300 && document.querySelector('[data-template-thumb]'); i++) await wait(200);
    if (document.querySelector('[data-template-thumb]')) throw new Error('snapshots not drawn');
    return [...document.querySelectorAll('img[data-template-id]')].map((i) => ({ id: i.dataset.templateId, key: i.dataset.thumbKey, src: i.src }));
  `);
  mkdirSync(dir, { recursive: true });
  const list = {};
  shots.forEach((s) => {
    writeFileSync(join(dir, s.id + ".jpg"), Buffer.from(s.src.replace(/^data:image\/jpeg;base64,/, ""), "base64"));
    list[s.id] = { src: "images/templates/model-3d/" + s.id + ".jpg", key: s.key };
  });
  writeFileSync(join(app, "template-thumbs.js"),
    "// The library's template thumbnails -- GENERATED by tools/template-thumbs.mjs\n" +
    "// (see that script, and templateThumb in app.js). Don't edit by hand.\n" +
    "window.TEMPLATE_MODEL_THUMBS = " + JSON.stringify(list, null, 1) + ";\n");
  a.log(shots.length + " template thumbnails written");
}
