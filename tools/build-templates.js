// Regenerates app/templates.js (the Rollcage library's built-in design
// templates) from the rollcage exports in ../design-samples. Every photo is
// stripped and the logbook date cleared -- templates never carry pictures.
// Run from anywhere:  node app/tools/build-templates.js
const fs = require("fs");
const path = require("path");

const SAMPLES_DIR = path.join(__dirname, "..", "..", "design-samples");
const OUT_FILE = path.join(__dirname, "..", "templates.js");

// Listed in library order; `name` overrides the export's own vehicle name.
const TEMPLATES = [
  { id: "rally-cage-double-v", file: "Rally cage 1.json", name: "Rally cage double V" },
  { id: "rally-cage-double-x", file: "Rally cage 2.json", name: "Rally cage double X" },
  { id: "road-racing", file: "Road racing.json" },
  { id: "half-rollcage", file: "Rollbar _ half rollcage.json" },
];

const out = TEMPLATES.map((t) => {
  const d = JSON.parse(fs.readFileSync(path.join(SAMPLES_DIR, t.file), "utf8"));
  const answers = {};
  Object.entries(d.answers || {}).forEach(([k, v]) => { answers[k] = { ...v, photos: [] }; });
  return {
    templateId: t.id,
    vehicle: { ...d.vehicle, name: t.name || d.vehicle.name, logbookDate: "" },
    pathId: d.pathId || "new_construction",
    answers,
  };
});

const header = `// Built-in design templates listed in the Rollcage library (see
// renderLibrary) -- GENERATED by tools/build-templates.js from the
// design-samples/*.json exports, with every photo stripped (templates never
// carry pictures, vehicle photos or homologation paperwork). Starting from
// one opens an unsaved copy under a fresh sessionId; the template itself is
// never modified. Don't edit by hand -- re-run the script instead.
`;
fs.writeFileSync(OUT_FILE, header + "window.ROLLCAGE_TEMPLATES = " + JSON.stringify(out) + ";\n");
console.log("Wrote " + out.length + " templates: " + out.map((t) => t.vehicle.name).join(", "));
