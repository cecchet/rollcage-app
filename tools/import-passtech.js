// Regenerates app/sanctioning-bodies.js -- the rollover protection rules of
// every sanctioning body that requires a full roll cage, imported from
// PassTech (../../safety-gear-check, src/data). Part 6 checks a cage
// against the selected one (see app.js's evaluatePassTechRollover).
// NASA Rally Sport, ARA and CARS Performance Rally are left out: they have
// their own full FIA 253 checklists in rules-data.js.
// Run:  node app/tools/import-passtech.js   (needs PassTech's node_modules)
const fs = require("fs");
const path = require("path");

const PASSTECH = path.join(__dirname, "..", "..", "..", "safety-gear-check");
const OUT_FILE = path.join(__dirname, "..", "sanctioning-bodies.js");
const HAS_FULL_CHECKLIST = new Set(["nasa-rallysport", "ara-performance-rally", "cars-performance-rally"]);
// Requires a welded 6-point cage with door bars and diagonals, but its
// PassTech rule doesn't set the full-cage flag.
const ALSO_INCLUDE = new Set(["sccnh-gravel-trials"]);

const { createJiti } = require(path.join(PASSTECH, "node_modules", "jiti"));
const jiti = createJiti(path.join(PASSTECH, "import.js"), { fsCache: false });
const { ALL_RULESETS } = jiti(path.join(PASSTECH, "src", "data", "index.ts"));
const { BUILD_DATE: version } = jiti(path.join(PASSTECH, "src", "lib", "version.ts"));

const requiresCage = (rule) => rule && rule.requirement === "required" && rule.rolloverProtectionRequiresFullCage === true;
const out = ALL_RULESETS
  .filter((r) => !HAS_FULL_CHECKLIST.has(r.id))
  .filter((r) => requiresCage(r.categories.rollover_protection) || ALSO_INCLUDE.has(r.id))
  .map((r) => {
    const overrides = Object.fromEntries(
      Object.entries(r.classOverrides || {})
        .filter(([, v]) => v.rollover_protection)
        .map(([k, v]) => [k, v.rollover_protection])
    );
    return {
      id: r.id,
      bodyId: r.bodyId,
      bodyName: r.bodyName,
      disciplineName: r.disciplineName,
      disciplineGroup: r.disciplineGroup,
      lastReviewed: r.lastReviewed,
      rule: r.categories.rollover_protection,
      // Only the classes whose rollover rule differs from the base one.
      classes: (r.classes || []).filter((c) => overrides[c.id]),
      classOverrides: overrides,
    };
  })
  .sort((a, b) => (a.disciplineGroup + a.bodyName + a.disciplineName).localeCompare(b.disciplineGroup + b.bodyName + b.disciplineName));

const header = `// Rollover protection rules of the sanctioning bodies that require a full
// roll cage -- GENERATED by tools/import-passtech.js from PassTech
// (safety-gear-check${version ? " " + version : ""}, src/data). Don't edit by hand; re-run the script.
`;
fs.writeFileSync(OUT_FILE, header + "window.PASSTECH_ROLLOVER_RULES = " + JSON.stringify(out) + ";\n");
console.log("Wrote " + out.length + " rulesets:\n  " + out.map((r) => r.id + (r.classes.length ? " (" + r.classes.length + " class overrides)" : "")).join("\n  "));
